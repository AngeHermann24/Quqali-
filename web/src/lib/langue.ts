/** Remplace les variables `{nom}` dans un gabarit. */
export const fmt = (tpl: ValeurTrad, vars: Record<string, string | number>) =>
  (typeof tpl === "function" ? tpl(0) : tpl).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));

/** Interpole la variable `{n}` (comptes) — ou appelle la fonction de pluralisation. */
export const tv = (v: ValeurTrad, n: number) => (typeof v === "function" ? v(n) : v.replace(/\{n\}/g, String(n)));

